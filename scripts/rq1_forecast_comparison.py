#!/usr/bin/env python3
"""
RQ1 (part B) — Forecasting country-level mean achievement: Random Forest and
XGBoost vs time-series models, across ILSA programs and domains.

Input  data/country_panel/ilsa_country_means.csv   (schema: data/country_panel/README.md)
Output outputs/rq1_forecast/
  predictions.csv                 every forecast (series × origin × model)
  accuracy_overall.csv            RMSE / MAE / bias / MAE relative to naive, per model
  accuracy_by_program_domain.csv  same, per program × domain (× grade)
  accuracy_by_origin.csv          same, per forecast origin cycle (shows e.g. the 2022 break)
  dm_tests.csv                    country-clustered Diebold–Mariano tests (RF/XGB vs each TS model, RF vs XGB)
  rq1_forecast_summary.md         auto-generated summary

Models
  time series (per country): Naive, Mean, Drift, Holt_damped, ARIMA (AICc-selected low order)
  global (pooled over all series): Panel_AR (pooled ridge on lags), RandomForest, XGBoost
All models predict the next cycle from information available at the origin cycle;
the comparison is restricted to forecast points produced by every model.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from src.forecasting.evaluation import accuracy, common_points, dm_table, rolling_origin  # noqa: E402
from src.forecasting.models import (  # noqa: E402
    LOCAL_MODELS,
    PanelRegression,
    RandomForestChange,
    XGBoostChange,
)
from src.forecasting.panel import build_supervised, load_panel  # noqa: E402

DEFAULT_PANEL = PROJECT_ROOT / "data" / "country_panel" / "ilsa_country_means.csv"
DEFAULT_OUT = PROJECT_ROOT / "outputs" / "rq1_forecast"
LAG_FEATURES = ["d1", "dev_from_mean", "group_mean_d1", "rel_to_group", "gap_years"]


def global_models(feature_columns: list[str], seed: int) -> dict:
    return {
        "Panel_AR": lambda train: PanelRegression("Panel_AR", LAG_FEATURES, alpha=1.0),
        "RandomForest": lambda train: RandomForestChange("RandomForest", feature_columns, random_state=seed),
        "XGBoost": lambda train: XGBoostChange("XGBoost", feature_columns, random_state=seed),
    }


def _md(df: pd.DataFrame, cols: list[str]) -> str:
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df[cols].iterrows():
        lines.append("| " + " | ".join(f"{v:.3f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--panel", type=Path, default=DEFAULT_PANEL)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--min-train-cycles", type=int, default=3)
    parser.add_argument("--min-train-rows", type=int, default=30)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    if not args.panel.exists():
        sys.exit(
            f"Panel file not found: {args.panel}\n"
            "Create it from the official OECD/IEA country means — see data/country_panel/README.md."
        )
    out = args.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)

    panel = load_panel(args.panel)
    sup = build_supervised(panel)
    preds = rolling_origin(
        panel,
        sup.frame,
        local_models=LOCAL_MODELS,
        global_models=global_models(sup.feature_columns, args.seed),
        min_train_cycles=args.min_train_cycles,
        min_train_rows=args.min_train_rows,
    )
    if preds.empty:
        sys.exit("No forecast points: the panel needs ≥ min-train-cycles + 1 cycles per series.")
    preds.to_csv(out / "predictions.csv", index=False)
    fair = common_points(preds)

    overall = accuracy(fair)
    overall.to_csv(out / "accuracy_overall.csv", index=False)
    by_pd = accuracy(fair, ["program", "domain", "grade"])
    by_pd.to_csv(out / "accuracy_by_program_domain.csv", index=False)
    by_origin = accuracy(fair, ["program", "origin_year"])
    by_origin.to_csv(out / "accuracy_by_origin.csv", index=False)

    ts_models = list(LOCAL_MODELS)
    pairs = [(ml, ts) for ml in ("RandomForest", "XGBoost") for ts in ts_models + ["Panel_AR"]]
    pairs.append(("XGBoost", "RandomForest"))
    dm = dm_table(fair, pairs)
    dm.to_csv(out / "dm_tests.csv", index=False)

    best_ts = overall[overall["model_kind"] == "time_series"].iloc[0]["model"]
    lines = [
        "# RQ1 (B) — Country-level forecasting: RF / XGBoost vs time-series models",
        "",
        "_Auto-generated by `scripts/rq1_forecast_comparison.py`._",
        "",
        f"- Panel: **{panel['country_code'].nunique()}** countries, "
        f"**{panel.groupby(['program', 'domain', 'grade']).ngroups}** program × domain series groups, "
        f"cycles {panel['year'].min()}–{panel['year'].max()}.",
        f"- Forecast points compared (all models available): **{len(fair) // fair['model'].nunique()}**.",
        f"- Best time-series model overall (RMSE): **{best_ts}**.",
        "",
        "## Overall accuracy (next-cycle forecasts, score points)",
        "",
        _md(overall, ["model", "model_kind", "n_forecasts", "RMSE", "MAE", "Bias", "RelMAE_vs_naive"]),
        "",
        "## Diebold–Mariano tests (squared error; negative mean = first model better; country-clustered)",
        "",
        _md(dm, ["model_a", "model_b", "n", "n_clusters", "mean_loss_diff", "t", "p_value"]),
        "",
        "Per program × domain and per origin results are in the CSV files of this folder.",
    ]
    (out / "rq1_forecast_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""
Build the predictor-level knowledge base used for RQ2 (literature → forecasting).

Writes outputs/knowledge_base/:
  predictor_mentions.csv          every top predictor of every achievement finding (+ 'considered' rows)
  predictor_evidence.csv          aggregated evidence per (scope, predictor group/domain)
  country_covariate_priors.json   priors for the country-level covariates in config/kb_covariate_map.json
                                  (scope 'all' plus one block per program / domain scope)
  knowledge_base_summary.md       auto-generated overview

The corpus folder is read only.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from src.analysis.corpus import load_corpus  # noqa: E402
from src.knowledge.predictor_kb import (  # noqa: E402
    build_predictor_evidence,
    country_covariate_priors,
    load_covariate_map,
    predictor_mentions,
)

DEFAULT_OUT = PROJECT_ROOT / "outputs" / "knowledge_base"
DEFAULT_MAP = PROJECT_ROOT / "config" / "kb_covariate_map.json"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--covariate-map", type=Path, default=DEFAULT_MAP)
    parser.add_argument("--min-studies", type=int, default=2)
    args = parser.parse_args()
    out = args.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)

    articles, _warnings = load_corpus()
    mentions = predictor_mentions(articles)
    mentions.to_csv(out / "predictor_mentions.csv", index=False)
    evidence = build_predictor_evidence(mentions)
    evidence.to_csv(out / "predictor_evidence.csv", index=False)

    cov_map = load_covariate_map(args.covariate_map)
    priors = {
        scope: country_covariate_priors(evidence, cov_map, scope=scope, min_studies=args.min_studies)
        for scope in sorted(evidence["scope"].unique())
    }
    (out / "country_covariate_priors.json").write_text(
        json.dumps({"min_studies": args.min_studies, "priors": priors}, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )

    top = mentions[mentions["kind"] == "top"]
    allg = evidence[(evidence["scope"] == "all") & (evidence["level"] == "predictor_group")].head(15)
    lines = [
        "# Predictor knowledge base (RQ2)",
        "",
        "_Auto-generated by `scripts/build_predictor_knowledge_base.py`._",
        "",
        f"- Achievement-target studies contributing predictors: **{top['article_id'].nunique()}**",
        f"- Top-predictor mentions: **{len(top)}** across **{top['finding_id'].nunique()}** findings",
        f"- Mentions with a detected direction: **{int(top['direction'].isin(['positive', 'negative']).sum())}**",
        "",
        "## Most salient predictor groups (scope = all)",
        "",
        "| predictor_group | n_studies_top | salience | mean_rank | +/−/? | direction |",
        "|---|---|---|---|---|---|",
    ]
    for _, r in allg.iterrows():
        lines.append(
            f"| {r['predictor_group']} | {r['n_studies_top']} | {r['salience']} | {r['mean_rank']} | "
            f"{r['n_positive']}/{r['n_negative']}/{r['n_unspecified']} | {r['direction']} |"
        )
    lines += ["", "## Country-level covariate priors (scope = all)", "",
              "| covariate | n_studies_top | direction | sign | weight |", "|---|---|---|---|---|"]
    for cov, p in priors.get("all", {}).items():
        lines.append(f"| {cov} | {p['n_studies_top']} | {p['direction']} | {p['sign']} | {p['weight']} |")
    lines += [
        "",
        "Directions are detected from sentences of the standardized conclusion / outcome summary that "
        "mention the predictor; `unspecified` means no directional wording was found, not a null effect.",
    ]
    (out / "knowledge_base_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
